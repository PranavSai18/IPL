const TEAMS_LIST = ['CSK', 'MI', 'RCB', 'KKR', 'SRH', 'DC', 'PBKS', 'RR', 'GT', 'LSG'];

function getRtmCardsCount(year, retCount) {
  const y = String(year);
  if (y === '2025') {
    return Math.max(0, 6 - retCount);
  } else if (y === '2024' || y === '2023') {
    return Math.max(0, 5 - retCount);
  } else {
    return Math.min(3, Math.max(0, 5 - retCount));
  }
}

/**
 * getInitialTeamsState
 * @param {string} auctionYear  - e.g. '2025'
 * @param {number} startingPurseNum - in CR (e.g. 120)
 * @param {string[]} teamNames  - optional override list
 * @param {string} auctionType  - 'mega' = Build From Scratch (no retentions), 'mini' = Retention mode
 */
function getInitialTeamsState(auctionYear, startingPurseNum, teamNames, auctionType) {
  const isScratch = auctionType === 'mega'; // 'mega' in code = Build From Scratch UI
  const is2025    = String(auctionYear) === '2025';
  const purseInRupees = (startingPurseNum !== undefined ? Number(startingPurseNum) : 120) * 10000000;

  const state = {};
  const listToUse = (Array.isArray(teamNames) && teamNames.length > 0) ? teamNames : TEAMS_LIST;

  listToUse.forEach(teamId => {
    if (isScratch) {
      // BUILD FROM SCRATCH — clean slate: full purse, no squad, no RTM
      state[teamId] = {
        teamId,
        userId: null,
        purse: purseInRupees,
        rtmCards: 0,        // RTM does not apply in scratch mode
        retentions: [],
        squad: [],
        retentionsLocked: false
      };
    } else {
      // RETENTION / MINI MODE — pre-load real retained players and deduct from purse
      let squad = [];
      let spent = 0;

      if (is2025 && retainedPlayersData2025[teamId]) {
        squad = retainedPlayersData2025[teamId].map(p => ({ ...p, isRetained: true }));
        spent = squad.reduce((sum, p) => sum + p.price, 0);
      }

      const remainingPurse = Math.max(0, purseInRupees - spent);
      const rtmCards = getRtmCardsCount(auctionYear, squad.length);

      state[teamId] = {
        teamId,
        userId: null,
        purse: remainingPurse,
        rtmCards,
        retentions: squad.map(p => p.name),
        squad,
        retentionsLocked: false
      };
    }
  });

  return state;
}

